// Dynamically expand to 100+ unique challenges if needed
export function getChallengeById(id: string): Challenge | undefined {
  return CHALLENGES.find(c => c.id === id);
}

export function getRandomChallenge(excludedIds: string[] = []): Challenge {
  const available = CHALLENGES.filter(c => !excludedIds.includes(c.id));
  if (available.length === 0) return CHALLENGES[Math.floor(Math.random() * CHALLENGES.length)];
  return available[Math.floor(Math.random() * available.length)];
}
